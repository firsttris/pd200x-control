//! pd200x-control desktop app. The logic lives in `pd200x-core` and
//! [`hub`]; this crate exposes it as typed Tauri commands and a tray icon.

pub mod commands;
pub mod hub;
mod tray;

use std::sync::Arc;
use std::thread;
use std::time::Duration;

use pd200x_core::pipewire::SystemRunner;
use pd200x_core::recording::SystemSpawner;
use pd200x_core::{flatpak, sim, store, Device};
use tauri::Manager;

/// All commands, for a given runtime. Expects `commands::*` in scope; used
/// by [`specta_builder`] and by the IPC tests with the mock runtime.
#[macro_export]
macro_rules! pd200x_commands {
    () => {
        tauri_specta::collect_commands![
            snapshot,
            level,
            apply_change,
            apply_eq,
            save_profile,
            rename_profile,
            delete_profile,
            set_boost,
            calibrate,
            apply_calibration,
            set_restore_on_connect,
            set_protected,
            start_recording,
            stop_recording,
            play_recording,
            recording_status,
        ]
    };
}

/// The command registry, shared by the app and the bindings export.
pub fn specta_builder() -> tauri_specta::Builder<tauri::Wry> {
    use commands::*;
    use pd200x_core::model::{Lighting, Tone};
    tauri_specta::Builder::<tauri::Wry>::new()
        .commands(pd200x_commands!())
        // Shared with the frontend and its mock backend, so neither repeats them.
        .constant("PRESETS", hub::presets_info())
        .constant("DEFAULT_TONE", Tone::default())
        .constant("DEFAULT_LIGHTING", Lighting::default())
        .constant("TARGET_PEAK_DB", pd200x_core::calibrate::TARGET_PEAK_DB)
        .constant("MAX_BOOST_DB", pd200x_core::pipewire::MAX_BOOST_DB)
        .constant("MAX_RECORDING_SECONDS", pd200x_core::recording::MAX_SECONDS)
}

/// Writes `src/lib/bindings.ts` for the frontend.
pub fn export_bindings(path: &std::path::Path) -> Result<(), String> {
    specta_builder()
        .export(
            specta_typescript::Typescript::default()
                .header("// @ts-nocheck\n// Generated by tauri-specta. Do not edit; run `just bindings`."),
            path,
        )
        .map_err(|e| e.to_string())
}

/// `PD200X_SIMULATOR=1` runs the app against a simulated microphone.
fn opener() -> hub::Opener {
    if std::env::var("PD200X_SIMULATOR").is_ok_and(|v| v == "1") {
        let sim = sim::Simulator::with_defaults();
        return Box::new(move || Ok(Device::new(Box::new(sim.clone()))));
    }
    Box::new(Device::open_system)
}

/// Opens the microphone when it is plugged in and reads the boost now and then.
fn watch(hub: Arc<hub::Hub>) {
    thread::Builder::new()
        .name("pd200x-watch".into())
        .spawn(move || {
            let mut tick = 0u64;
            loop {
                hub.connect();
                if tick.is_multiple_of(3) {
                    hub.refresh_boost();
                }
                tick = tick.wrapping_add(1);
                thread::sleep(Duration::from_secs(1));
            }
        })
        .expect("watcher thread");
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let hidden = std::env::args().any(|arg| arg == "--hidden");
    let mut context = tauri::generate_context!();
    // Decide visibility after the tray exists, before the first window is mapped.
    for window in &mut context.config_mut().app.windows {
        if window.label == "main" {
            window.visible = false;
        }
    }
    let config_dir = store::system_config_dir().expect("HOME must be set");
    let hub = Arc::new(hub::Hub::new(
        config_dir,
        hub::Host::system(),
        Box::new(SystemRunner),
        Box::new(SystemSpawner),
        opener(),
    ));
    let exit_hub = hub.clone();
    let builder = specta_builder();

    let flatpak_id = flatpak::id();
    // GTK names the window after the program (Wayland app_id, X11 WM_CLASS); in
    // the Flatpak that has to be the app ID, or the desktop does not match the
    // window to the Flatpak's desktop file. Prefixr does the same (src-tauri/src/lib.rs).
    if let Some(id) = &flatpak_id {
        glib::set_prgname(Some(id.as_str()));
    }
    // A Flatpak may only own D-Bus names below its app ID, and the default (the
    // Tauri identifier) is none, so a second start would open a second window.
    let single_instance = tauri_plugin_single_instance::Builder::new().callback(|app, args, _| {
        if !args.iter().any(|arg| arg == "--hidden") {
            tray::show_window(app);
        }
    });
    let single_instance = match flatpak_id {
        Some(id) => single_instance.dbus_id(id),
        None => single_instance,
    };

    tauri::Builder::default()
        .plugin(single_instance.build())
        // Opens the window again at the size and place it was left at.
        .plugin(
            tauri_plugin_window_state::Builder::default()
                .with_state_flags(
                    tauri_plugin_window_state::StateFlags::all() & !tauri_plugin_window_state::StateFlags::VISIBLE,
                )
                .build(),
        )
        .manage(hub.clone())
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            watch(hub);
            // Without a tray (no StatusNotifier host) closing the window quits as usual.
            let has_tray = matches!(tray::create(app.handle()), Ok(true));
            if has_tray {
                if let Some(window) = app.get_webview_window("main") {
                    let w = window.clone();
                    window.on_window_event(move |event| {
                        if let tauri::WindowEvent::CloseRequested { api, .. } = event {
                            api.prevent_close();
                            let _ = w.hide();
                        }
                    });
                }
            }
            if !hidden || !has_tray {
                tray::show_window(app.handle());
            }
            Ok(())
        })
        .build(context)
        .expect("error while building pd200x-control")
        .run(move |_, event| {
            if let tauri::RunEvent::Exit = event {
                // The temporary recording goes with the app.
                exit_hub.cleanup();
            }
        });
}
